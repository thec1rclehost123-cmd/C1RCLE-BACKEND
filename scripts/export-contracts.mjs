/**
 * ─── Export backend contracts into the frontend workspace (B02 / spec §5) ────
 *
 * Two repos, one wire contract. `packages/contracts` is backend-owned. Until a
 * versioned package is published, the frontend consumes a *generated* mirror:
 * this script copies `packages/contracts/src/**\/*.ts` into
 * `<frontend>/packages/contracts/src/**`, prepending a `GENERATED` header to
 * every file so nobody hand-edits the copy.
 *
 * It syncs `src/` ONLY — it never writes the frontend package scaffolding
 * (`package.json`, `tsconfig*.json`, `eslint.config.ts`, …). That is Phase 2's
 * job. Run Phase 2's scaffold first (or after — the order does not matter), then
 * run this whenever the contracts change.
 *
 * Usage:
 *   node scripts/export-contracts.mjs [--frontend <path>] [--dry-run]
 *
 * Frontend path resolution (same convention as scripts/contract-parity.mjs):
 *   1. --frontend <path>
 *   2. $C1RCLE_FRONTEND_PATH
 *   3. ../C1RCLE-FRONTEND (sibling of this repo)
 *
 * Exit 0 = synced (or already in sync). Exit 1 = the backend source is missing.
 */
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SOURCE_DIR = join(ROOT, 'packages/contracts/src');

const HEADER_PREFIX = '// GENERATED by C1RCLE-BACKEND/scripts/export-contracts.mjs';

function frontendRoot() {
  const flagIndex = process.argv.indexOf('--frontend');
  if (flagIndex !== -1 && process.argv[flagIndex + 1]) {
    return resolve(process.argv[flagIndex + 1]);
  }
  if (process.env.C1RCLE_FRONTEND_PATH) return resolve(process.env.C1RCLE_FRONTEND_PATH);
  return resolve(ROOT, '..', 'C1RCLE-FRONTEND');
}

const DRY_RUN = process.argv.includes('--dry-run');
const FRONTEND = frontendRoot();
const TARGET_DIR = join(FRONTEND, 'packages/contracts/src');

if (!existsSync(SOURCE_DIR) || !statSync(SOURCE_DIR).isDirectory()) {
  console.error(`export-contracts: backend source not found at ${SOURCE_DIR}`);
  process.exit(1);
}

/** Every `*.ts` file under `dir`, excluding tests, as paths relative to `dir`. */
function collectTsFiles(dir, base = dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      if (entry === 'node_modules' || entry === 'dist' || entry === '.turbo') continue;
      out.push(...collectTsFiles(full, base));
    } else if (entry.endsWith('.ts') && !entry.endsWith('.test.ts') && !entry.endsWith('.d.ts')) {
      out.push(relative(base, full));
    }
  }
  return out;
}

/** Files under `dir` that already carry our GENERATED header (relative paths). */
function collectGeneratedFiles(dir, base = dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      if (entry === 'node_modules' || entry === 'dist' || entry === '.turbo') continue;
      out.push(...collectGeneratedFiles(full, base));
    } else if (entry.endsWith('.ts')) {
      const firstLine = readFileSync(full, 'utf8').split('\n', 1)[0] ?? '';
      if (firstLine.startsWith(HEADER_PREFIX)) out.push(relative(base, full));
    }
  }
  return out;
}

const sourceFiles = collectTsFiles(SOURCE_DIR).sort();
const toPosix = (p) => p.split('\\').join('/');

const written = [];
const unchanged = [];
const removed = [];

for (const relPath of sourceFiles) {
  const sourcePosix = `packages/contracts/src/${toPosix(relPath)}`;
  const header = `${HEADER_PREFIX} — do not edit. Source: ${sourcePosix}\n`;
  const body = readFileSync(join(SOURCE_DIR, relPath), 'utf8');
  const nextContent = header + body;

  const targetPath = join(TARGET_DIR, relPath);
  const current = existsSync(targetPath) ? readFileSync(targetPath, 'utf8') : null;

  if (current === nextContent) {
    unchanged.push(relPath);
    continue;
  }
  if (!DRY_RUN) {
    mkdirSync(dirname(targetPath), { recursive: true });
    writeFileSync(targetPath, nextContent);
  }
  written.push(relPath);
}

// Drop generated files in the target that no longer have a backend source —
// keeps the mirror exact. Only ever touches files carrying our header.
const sourceSet = new Set(sourceFiles.map(toPosix));
for (const relPath of collectGeneratedFiles(TARGET_DIR)) {
  if (sourceSet.has(toPosix(relPath))) continue;
  if (!DRY_RUN) rmSync(join(TARGET_DIR, relPath));
  removed.push(relPath);
}

/* ── summary ────────────────────────────────────────────────────────────────── */
const verb = DRY_RUN ? 'would ' : '';
console.log(`export-contracts: ${FRONTEND}`);
console.log(`  target: ${TARGET_DIR}`);
console.log(
  `  ${verb}write ${written.length}, unchanged ${unchanged.length}, ${verb}remove ${removed.length}` +
    ` (of ${sourceFiles.length} source files)`,
);
for (const f of written) console.log(`  ${DRY_RUN ? '~' : '+'} ${toPosix(f)}`);
for (const f of removed) console.log(`  ${DRY_RUN ? '~' : '-'} ${toPosix(f)}`);
if (DRY_RUN && (written.length > 0 || removed.length > 0)) {
  console.log('  (dry run — nothing written)');
}
